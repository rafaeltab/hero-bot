import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { chmodSync, existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { parseEnv } from "node:util";
import {
  appEnv,
  databasePort,
  databaseUrl,
  gitDir,
  identityPath,
  portsAvailable,
  registry,
  registryPath,
  root,
  writePrivate,
} from "./state.mjs";

const required = [
  "DEV_DISCORD_BOT_TOKEN",
  "DEV_DISCORD_APPLICATION_ID",
  "DEV_DISCORD_GUILD_ID",
];
const optional = ["HERO_AI_API_KEY", "HERO_AI_MODEL"];
export async function configure() {
  const allocations = registry();
  let value = allocations[gitDir];
  if (!value) {
    for (let slot = 0; slot < 1000; slot++) {
      if (
        Object.values(allocations).some((entry) => entry.slot === slot) ||
        !(await portsAvailable(slot))
      )
        continue;
      value = { id: randomUUID(), slot, gitDir };
      allocations[gitDir] = value;
      writePrivate(registryPath, JSON.stringify(allocations));
      break;
    }
    if (!value) throw Error("No available worktree port range.");
  }
  writePrivate(identityPath, JSON.stringify(value));
  const secrets = join(
    process.env.XDG_CONFIG_HOME || join(homedir(), ".config"),
    "hero-bot/secrets.env",
  );
  // The common Git directory belongs to main, even from a linked checkout.
  const main = execFileSync(
    "git",
    ["-C", root, "worktree", "list", "--porcelain", "-z"],
    { encoding: "utf8" },
  )
    .split("\0")[0]
    .slice("worktree ".length);
  const source = existsSync(secrets) ? readFileSync(secrets, "utf8") : "";
  let imported = {};
  if (!existsSync(secrets)) {
    const mainEnv = join(main, "apps/discord-bot/.env");
    if (existsSync(mainEnv)) imported = parseEnv(readFileSync(mainEnv, "utf8"));
  }
  const values = parseEnv(source);
  let next = source;
  for (const key of [...required, ...optional]) {
    if (!(key in values)) {
      values[key] = imported[key] || "";
      next += `\n${key}=${encode(values[key])}\n`;
    }
  }
  writePrivate(secrets, next);
  chmodSync(secrets, 0o600);
  const template = readFileSync(
    join(root, "apps/discord-bot/.env.example"),
    "utf8",
  );
  const generated = parseEnv(template);
  for (const key of [...required, ...optional]) generated[key] = values[key];
  generated.HERO_ENV = "development";
  generated.DATABASE_URL = databaseUrl(value);
  generated.HERO_TEST_DATABASE_URL = databaseUrl(value);
  writePrivate(
    appEnv,
    `# Generated by make install. Edit ${secrets} for persistent credentials.\n${Object.entries(
      generated,
    )
      .map(([key, setting]) => `${key}=${encode(setting)}`)
      .join("\n")}\n`,
  );
  const missing = required.filter((key) => !values[key]);
  if (missing.length)
    console.warn(
      `Unconfigured development keys: ${missing.join(", ")}. Offline work is available.`,
    );
  console.log(
    `Configured worktree slot ${value.slot}, PostgreSQL port ${databasePort(value)}. Setup started no services.`,
  );
}
function encode(value) {
  // Node dotenv accepts literal newlines in quoted values. Never source this file as shell code.
  if (!value.includes("'")) return `'${value}'`;
  if (!value.includes('"')) return `"${value}"`;
  if (!value.includes("`")) return `\`${value}\``;
  throw Error(
    "A secret contains all dotenv quote delimiters; unable to encode it safely.",
  );
}
